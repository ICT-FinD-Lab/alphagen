def read_alphagpt_init_pool(seed: int) -> List[Expression]:
    DIR = "./out/llm-tests/interaction"
    parser = build_parser()
    for path in Path(DIR).glob(f"v0_{seed}*"):
        with open(path / "report.json") as f:
            data = json.load(f)
            pool_state = data[-1]["pool_state"]
            return [parser.parse(expr) for expr, _ in pool_state]
    return []


def build_parser() -> ExpressionParser:
    return ExpressionParser(
        Operators,
        ignore_case=True,
        non_positive_time_deltas_allowed=False,
        additional_operator_mapping={
            "Max": ["Greater"],
            "Min": ["Less"],
            "Delta": ["Sub"]
        }
    )


def build_chat_client(log_dir: str) -> ChatClient:
    logger = get_logger("llm", os.path.join(log_dir, "llm.log"))
    return OpenAIClient(
        client=OpenAI(),
        config=ChatConfig(
            system_prompt=EXPLAIN_WITH_TEXT_DESC,
            logger=logger
        )
    )


class CustomCallback(BaseCallback):
           
    def __init__(
        self,
        save_path: str,
        test_calculators: List[QLibStockDataCalculator],
        verbose: int = 0,
        chat_session: Optional[InterativeSession] = None,
        llm_every_n_steps: int = 25_000,
        drop_rl_n: int = 5,
        hyperparameters: Optional[Dict[str, Any]] = None
    ):
        super().__init__(verbose)
        self.save_path = save_path
        self.test_calculators = test_calculators
        os.makedirs(self.save_path, exist_ok=True)

        self.llm_use_count = 0
        self.last_llm_use = 0
        self.obj_history: List[Tuple[int, float]] = []
        self.llm_every_n_steps = llm_every_n_steps
        self.chat_session = chat_session
        self._drop_rl_n = drop_rl_n
        self.hyperparameters = hyperparameters or {}
        self.start_time = datetime.now()
        self.metrics_history: List[Dict[str, Any]] = []
        # Track alpha origins and survival
        self.alpha_origins: Dict[int, str] = {}  # alpha_id -> 'llm' or 'rl'
        self.alpha_birth_times: Dict[int, int] = {}  # alpha_id -> timestep born
        self.alpha_survival_history: Dict[int, Dict[str, Any]] = {}  # alpha_id -> survival data
        self.expr_to_id: Dict[str, int] = {}  # expression string -> unique id
        self.llm_expr_strs: set = set()  # Expressions generated by LLM (from initial pool load)
        self.improvement_expr_strs: set = set()  # Expressions from improvement LLM
        self.next_alpha_id = 0
        # For LLM/improvement LLM alpha stats
        self.llm_alpha_stats = init_llm_alpha_stats()

    def register_llm_pool_exprs(self, exprs: List[Expression]) -> None:
        """Register LLM-generated expressions from initial pool load."""
        for expr in exprs:
            self.llm_expr_strs.add(str(expr))
        print(f"[DEBUG] Registered {len(exprs)} initial LLM-generated expressions")
    
    def _on_step(self) -> bool:
        return True

    def _on_rollout_end(self) -> None:
        # Track alpha births and deaths before recording metrics
        self._update_alpha_tracking()
        
        if self.chat_session is not None:
            self._try_use_llm()

        self.logger.record('pool/size', self.pool.size)
        self.logger.record('pool/significant', (np.abs(self.pool.weights[:self.pool.size]) > 1e-4).sum())
        self.logger.record('pool/best_ic_ret', self.pool.best_ic_ret)
        self.logger.record('pool/eval_cnt', self.pool.eval_cnt)
        n_days = sum(calculator.data.n_days for calculator in self.test_calculators)
        ic_test_mean, rank_ic_test_mean = 0., 0.
        for i, test_calculator in enumerate(self.test_calculators, start=1):
            ic_test, rank_ic_test = self.pool.test_ensemble(test_calculator)
            ic_test_mean += ic_test * test_calculator.data.n_days / n_days
            rank_ic_test_mean += rank_ic_test * test_calculator.data.n_days / n_days
            self.logger.record(f'test/ic_{i}', ic_test)
            self.logger.record(f'test/rank_ic_{i}', rank_ic_test)
        self.logger.record(f'test/ic_mean', ic_test_mean)
        self.logger.record(f'test/rank_ic_mean', rank_ic_test_mean)
        
        # Record metrics for report
        self.metrics_history.append({
            'timestep': self.num_timesteps,
            'pool_size': self.pool.size,
            'pool_significant': int((np.abs(self.pool.weights[:self.pool.size]) > 1e-4).sum()),
            'best_ic_ret': float(self.pool.best_ic_ret),
            'ic_test_mean': float(ic_test_mean),
            'rank_ic_test_mean': float(rank_ic_test_mean)
        })
        
        self.save_checkpoint()

    def _update_alpha_tracking(self) -> None:
        """Track birth/death of alphas in the pool."""
        state = self.pool.state
        current_exprs = {str(state['exprs'][i]): i for i in range(self.pool.size)}
        
        # Mark new alphas
        for expr_str in current_exprs:
            if expr_str not in self.expr_to_id:
                alpha_id = self.next_alpha_id
                self.next_alpha_id += 1
                self.expr_to_id[expr_str] = alpha_id
                self.alpha_birth_times[alpha_id] = self.num_timesteps
                # Determine origin: check if LLM, improvement, or RL
                if expr_str in self.llm_expr_strs:
                    self.alpha_origins[alpha_id] = 'llm'
                    origin = 'llm'
                elif expr_str in self.improvement_expr_strs:
                    self.alpha_origins[alpha_id] = 'improvement'
                    origin = 'improvement'
                else:
                    self.alpha_origins[alpha_id] = 'rl'
                    origin = 'rl'
                self.alpha_survival_history[alpha_id] = {
                    'alpha_id': alpha_id,
                    'expression': expr_str,
                    'origin': origin,
                    'birth_timestep': self.num_timesteps,
                    'death_timestep': None,
                    'survival_steps': None
                }
        
        # Mark alphas that died (were removed)
        for expr_str, alpha_id in list(self.expr_to_id.items()):
            if expr_str not in current_exprs and self.alpha_survival_history[alpha_id]['death_timestep'] is None:
                self.alpha_survival_history[alpha_id]['death_timestep'] = self.num_timesteps
                self.alpha_survival_history[alpha_id]['survival_steps'] = (
                    self.num_timesteps - self.alpha_birth_times[alpha_id]
                )

    def save_checkpoint(self):
        path = os.path.join(self.save_path, f'{self.num_timesteps}_steps')
        self.model.save(path)   # type: ignore
        if self.verbose > 1:
            print(f'Saving model checkpoint to {path}')
        with open(f'{path}_pool.json', 'w') as f:
            json.dump(self.pool.to_json_dict(), f)

    def show_pool_state(self):
        state = self.pool.state
        print('---------------------------------------------')
        for i in range(self.pool.size):
            weight = state['weights'][i]
            expr_str = str(state['exprs'][i])
            ic_ret = state['ics_ret'][i]
            print(f'> Alpha #{i}: {weight}, {expr_str}, {ic_ret}')
        print(f'>> Ensemble ic_ret: {state["best_ic_ret"]}')
        print('---------------------------------------------')

    def _try_use_llm(self) -> None:
        n_steps = self.num_timesteps
        if n_steps - self.last_llm_use < self.llm_every_n_steps:
            return
        self.last_llm_use = n_steps
        self.llm_use_count += 1
        
        assert self.chat_session is not None
        self.chat_session.client.reset()
        logger = self.chat_session.logger
        logger.debug(
            f"[Step: {n_steps}] Trying to invoke LLM (#{self.llm_use_count}): "
            f"IC={self.pool.best_ic_ret:.4f}, obj={self.pool.best_ic_ret:.4f}")

        try:
            remain_n = max(0, self.pool.size - self._drop_rl_n)
            remain = self.pool.most_significant_indices(remain_n)
            
            # Record LLM alphas before they're added
            pre_llm_exprs = {str(self.pool.state['exprs'][i]) for i in range(self.pool.size)}
            
            self.pool.leave_only(remain)
            self.chat_session.update_pool(self.pool)
            
            # Track newly added alphas as LLM-generated for origin marking
            post_llm_exprs = {str(self.pool.state['exprs'][i]) for i in range(self.pool.size)}
            new_exprs = post_llm_exprs - pre_llm_exprs
            # Add to the set so they'll be marked as 'llm' origin when tracked
            self.llm_expr_strs.update(new_exprs)
            print(f"[DEBUG] Marked {len(new_exprs)} new alphas as LLM-generated")
        except Exception as e:
            logger.warning(f"LLM invocation failed due to {type(e)}: {str(e)}")

